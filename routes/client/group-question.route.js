const express = require("express");
const router = express.Router({ mergeParams: true });
const controller = require("../../controllers/client/group-question.controller");
const auth = require("../../middlewares/auth.middleware");
router.use(auth.requireAuth, controller.requireOwner);
router.get("/", controller.index);
router.post("/create", controller.create);
router.patch("/:questionId", controller.update);
router.delete("/:questionId", controller.remove);
module.exports = router;
