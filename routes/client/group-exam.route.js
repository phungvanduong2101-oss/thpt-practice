const express = require("express");
const router = express.Router({ mergeParams: true });
const controller = require("../../controllers/client/group-exam.controller");
const auth = require("../../middlewares/auth.middleware");
const taking = require("../../controllers/client/group-exam-taking.controller");
router.use(auth.requireAuth);
router.get("/", taking.requireMember, taking.index);
router.get("/:examId/take", taking.requireMember, taking.detail);
router.post("/:examId/start", taking.requireMember, taking.start);
router.use(controller.requireOwner);
router.get("/manage", controller.index);
router.get("/questions", controller.questions);
router.post("/create", controller.create);
router.patch("/:examId", controller.update);
router.delete("/:examId", controller.remove);
module.exports = router;
